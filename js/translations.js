function localizeRationaleText(text) {
  if (!text || typeof text !== 'string') return text || '';
  const { map, pattern } = buildRationaleLocalizerMap();
  return text.replace(pattern, (match) => {
    const direct = map.get(match);
    if (direct) return `【${direct}】`;
    const lowerMatch = map.get(match.toLowerCase());
    if (lowerMatch) return `【${lowerMatch}】`;
    return match;
  });
}

