// 全局宝可梦名称翻译辅助函数
function translatePokemonToZh(pokemonName) {
  if (!pokemonName) return '';
  const trimmed = pokemonName.trim();
  const allMons = (typeof window !== 'undefined' && window.CHAMPIONS_DATA && window.CHAMPIONS_DATA.pokemon) 
    ? window.CHAMPIONS_DATA.pokemon 
    : (typeof allPokemonList !== 'undefined' ? allPokemonList : []);
  
  let isMega = trimmed.startsWith('Mega ');
  let baseName = trimmed.replace(/^Mega\s+/, '').replace(/\s+[XYZ]$/, '');
  let branch = '';
  if (trimmed.endsWith(' Y')) branch = ' Y';
  else if (trimmed.endsWith(' X')) branch = ' X';
  else if (trimmed.endsWith(' Z')) branch = ' Z';

  const found = allMons.find(p => 
    (p.enName && p.enName.toLowerCase() === baseName.toLowerCase()) ||
    (p.nameEn && p.nameEn.toLowerCase() === baseName.toLowerCase()) ||
    (p.slug && p.slug.toLowerCase() === baseName.toLowerCase()) ||
    (p.name && p.name === baseName)
  );
  if (found && found.name) {
    return isMega ? `超级${found.name}${branch}` : found.name;
  }
  return trimmed;
}

