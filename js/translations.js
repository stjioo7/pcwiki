// 全局道具翻译辅助函数
function translateItemToZh(itemName) {
  if (!itemName) return '';
  const trimmed = itemName.trim();
  if (CHAMPIONS_ITEMS_ZH[trimmed]) return CHAMPIONS_ITEMS_ZH[trimmed];
  if (CHAMPIONS_ITEMS_ZH[trimmed.toLowerCase()]) return CHAMPIONS_ITEMS_ZH[trimmed.toLowerCase()];

  // 动态解析各类 Mega 进化石
  const allMons = (typeof window !== 'undefined' && window.CHAMPIONS_DATA && window.CHAMPIONS_DATA.pokemon) 
    ? window.CHAMPIONS_DATA.pokemon 
    : (typeof allPokemonList !== 'undefined' ? allPokemonList : []);

  for (const p of allMons) {
    if (p.mega && p.mega.forms) {
      for (const form of p.mega.forms) {
        if (form.megaStone && (form.megaStone.toLowerCase() === trimmed.toLowerCase() || (form.megaStoneEn && form.megaStoneEn.toLowerCase() === trimmed.toLowerCase()))) {
          return form.megaStone;
        }
      }
    }
  }

  if (trimmed.endsWith('ite') || trimmed.includes('ite ')) {
    const base = trimmed.replace(/ite(\s+[XYZxyz])?$/i, '');
    const mon = allMons.find(p => (p.enName && p.enName.toLowerCase().startsWith(base.toLowerCase())) || (p.nameEn && p.nameEn.toLowerCase().startsWith(base.toLowerCase())));
    if (mon) {
      const branchMatch = trimmed.match(/\s+([XYZxyz])$/i);
      const suffix = branchMatch ? ` ${branchMatch[1].toUpperCase()}` : '';
      return `${mon.name}进化石${suffix}`;
    }
  }

  return trimmed;
}

